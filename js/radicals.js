// 部首の名前。左がわ（へん）にあるときは「〜へん」
KG.radicalName = function (info) {
  if (!info) return '';
  if (info.p === 'left' && KG.RADICAL_HEN[info.r]) return KG.RADICAL_HEN[info.r];
  return KG.RADICAL_NAMES[info.r] || '';
};

// 字の一覧を、部首ごとにまとめる。多いまとまりから順に
KG.radicalGroups = function (chars) {
  if (!KG.RADICALS) return [];
  const map = new Map();
  for (const c of chars) {
    const info = KG.RADICALS[c];
    if (!info) continue;
    if (!map.has(info.r)) map.set(info.r, { r: info.r, chars: [], pos: {} });
    const g = map.get(info.r);
    g.chars.push(c);
    g.pos[info.p] = (g.pos[info.p] || 0) + 1;
  }
  return [...map.values()].map(g => {
    // いちばん多い位置の名前にする（木なら「きへん」が多い、など）
    const p = Object.entries(g.pos).sort((a, b) => b[1] - a[1])[0][0];
    return { ...g, name: KG.radicalName({ r: g.r, p }) };
  }).sort((a, b) => b.chars.length - a.chars.length);
};
